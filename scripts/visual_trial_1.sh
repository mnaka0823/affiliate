#!/usr/bin/env bash
# ビジュアル試作1：アイコン4案＋見出し画像3案（計7枚＝APIを7回呼ぶ。料金がかかる）
#   確認だけ（APIを呼ばない）: scripts/visual_trial_1.sh --dry-run
#   実行:                       scripts/visual_trial_1.sh
# 保存先: images/output/trial-1/（git に入らない）。スタイルは knowledge/visual-style.md を参照。
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="images/output/trial-1"
EXTRA=("$@")

COMMON="フラットなベクター風のイラスト。単純な形で、角を少し丸めた角丸の形を基本にする。影とグラデーションなし、輪郭線なし。背景は無地の淡い青灰色（#EAF2F8）。濃紺（#1D3557）、青（#2F6DB5）、ティール（#2A9D8F）を基調にし、差し色の黄色（#F2B705）を1か所だけ小さく使う。落ち着いて信頼できる雰囲気。人物の顔は描かない。ロゴ・商標・実在の企業や官公庁の表現を入れない。怖さや不安を煽る表現を入れない。余白を広く取る。"
ICON="アカウントのアイコン用。正方形の中央の円に収まる大きさで、主役は1つだけ。太く単純な形で、小さく表示しても読める。文字は入れない。"

gen() { # name size prompt
  python3 scripts/image.py generate --out "$OUT" --name "$1" --size "$2" -p "$COMMON $3" "${EXTRA[@]}"
}

gen icon-1 1024x1024 "$ICON 正面から見た閉じた手帖を中央に大きく1冊。表紙は青、ティールのしおりひも、表紙に大きな黄色のチェックマークを1つ。"
gen icon-2 1024x1024 "$ICON 開いた手帖を中央に1冊。左右のページにチェックボックスと横線を3行ずつ。1行目のチェックボックスだけ黄色のチェックマーク。"
gen icon-3 1024x1024 "$ICON 手帖1冊と、斜めに置いた鉛筆1本。手帖の表紙に白いチェックマーク、鉛筆の先端だけ黄色。"
gen icon-4 1024x1024 "$ICON 角丸の四角いバッジの中に、手帖の簡略なシルエットとチェックマークだけ。極端に単純にして、48pxに縮めても形が分かる太さにする。"

HEADER="記事の見出し画像用。横長。主役は縦の中央の帯（高さの約55%）に収め、上下は無地の背景だけにする。"
gen header-1 1536x1024 "$HEADER 中央に大きなスマホを1台。画面にチェックリスト（チェックボックスと線）、1つ目だけ黄色のチェック。スマホの下に、太い角丸ゴシックで日本語の文字「最初の30分」を入れる。"
gen header-2 1536x1024 "$HEADER 中央に大きな丸い時計を1つ。30分ぶんの扇形だけ黄色で塗り、時計の中央に白いチェックマーク。時計の下に、太い角丸ゴシックで日本語の文字「最初の30分」を入れる。"
gen header-3 1536x1024 "$HEADER 中央にスマホ1台と、その横に大きな鍵を1つ。鍵はティールで、閉じて安心できる印象にする。文字は入れない。"
